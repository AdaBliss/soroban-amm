#!/usr/bin/env node
// Keeps the webhook-streamer event schema file honest.
//
//   node scripts/check_event_schemas.mjs              check (used in CI)
//   node scripts/check_event_schemas.mjs --write-docs regenerate the catalogue
//                                                     in docs/event-schema-versioning.md
//
// The check fails when
//   - a contract emits an event (or an arity of one) that
//     services/webhook-streamer/src/event-schemas.json does not describe,
//   - the schema file describes an event no contract emits any more, or
//   - the generated catalogue in docs/event-schema-versioning.md is stale.
// So changing a Rust emit site without updating the schema (or the other way
// round) fails CI instead of silently mislabelling webhook payloads.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { extractEmitSites } from "./event_emit_sites.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_PATH = join(ROOT, "services/webhook-streamer/src/event-schemas.json");
const DOCS_PATH = join(ROOT, "docs/event-schema-versioning.md");
const BEGIN = "<!-- BEGIN GENERATED EVENT FIELD CATALOGUE -->";
const END = "<!-- END GENERATED EVENT FIELD CATALOGUE -->";

export function renderCatalogue(schema) {
  const lines = [
    BEGIN,
    "<!-- Generated by scripts/check_event_schemas.mjs --write-docs from",
    "     services/webhook-streamer/src/event-schemas.json. Do not edit by hand. -->",
    "",
    "## Webhook field catalogue (generated)",
    "",
    "Every event the deployed contracts emit, with the named payload fields the",
    "webhook-streamer delivers. `Topics` counts the on-chain topics (the first is the",
    "event name; any others, such as the trader or provider, are indexed addresses).",
    "An event listed more than once has several payload shapes, told apart by field",
    "count. Events marked unversioned carry their payload without the",
    "`(EVENT_SCHEMA_VERSION, payload)` envelope.",
    "",
  ];
  for (const [kind, { events }] of Object.entries(schema.kinds)) {
    lines.push(`### \`${kind}\``, "", "| Event | Topics | Payload fields | Envelope |", "|---|---|---|---|");
    for (const [name, variants] of Object.entries(events)) {
      for (const v of variants) {
        const fields = v.fields.length ? v.fields.map((f) => `\`${f}\``).join(", ") : "_none_";
        const shape = v.shape === "scalar" ? " (bare value)" : "";
        lines.push(
          `| \`${name}\` | ${v.topics} | ${fields}${shape} | ${v.versioned === false ? "unversioned" : `v${v.version}`} |`,
        );
      }
    }
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}

function sameShape(variant, site) {
  return (
    variant.fields.length === site.arity &&
    variant.topics === site.topics &&
    (variant.versioned !== false) === site.versioned &&
    (variant.shape === "scalar") === (site.shape === "scalar")
  );
}

export function findProblems(schema, sites, docs) {
  const problems = [];
  const covered = new Set();

  for (const site of sites) {
    const where = site.source;
    if (!site.event) {
      problems.push(`${where}: cannot read the event name from the first topic; teach scripts/event_emit_sites.mjs or use symbol_short!/Symbol::new with a literal`);
      continue;
    }
    const variants = schema.kinds[site.contract]?.events[site.event];
    if (!variants) {
      problems.push(`${where}: ${site.contract} emits "${site.event}" but event-schemas.json has no entry for it`);
      continue;
    }
    const index = variants.findIndex((v) => sameShape(v, site));
    if (index === -1) {
      const known = variants.map((v) => `${v.fields.length}`).join(", ");
      problems.push(
        `${where}: ${site.contract}.${site.event} is emitted with ${site.arity} payload field(s) and ${site.topics} topic(s) ` +
          `(${site.versioned ? "versioned" : "unversioned"}${site.shape === "scalar" ? ", bare value" : ""}), ` +
          `but event-schemas.json describes arity ${known}`,
      );
      continue;
    }
    covered.add(`${site.contract}.${site.event}#${index}`);
  }

  for (const [kind, { events }] of Object.entries(schema.kinds)) {
    if (!sites.some((s) => s.contract === kind)) {
      problems.push(`event-schemas.json lists contract "${kind}" but no contract directory of that name emits events`);
    }
    for (const [name, variants] of Object.entries(events)) {
      variants.forEach((v, i) => {
        if (!covered.has(`${kind}.${name}#${i}`)) {
          problems.push(`event-schemas.json: ${kind}.${name} (${v.fields.length} field(s)) is not emitted by any contract; remove it or fix the emit site`);
        }
      });
    }
  }

  const start = docs.indexOf(BEGIN);
  const end = docs.indexOf(END);
  if (start === -1 || end === -1) {
    problems.push("docs/event-schema-versioning.md has no generated field catalogue; run: node scripts/check_event_schemas.mjs --write-docs");
  } else if (docs.slice(start, end + END.length) !== renderCatalogue(schema)) {
    problems.push("docs/event-schema-versioning.md field catalogue is out of date; run: node scripts/check_event_schemas.mjs --write-docs");
  }
  return problems;
}

function main() {
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
  const docs = readFileSync(DOCS_PATH, "utf8");

  if (process.argv.includes("--write-docs")) {
    const catalogue = renderCatalogue(schema);
    const start = docs.indexOf(BEGIN);
    const end = docs.indexOf(END);
    const next =
      start === -1 || end === -1
        ? `${docs.trimEnd()}\n\n${catalogue}\n`
        : docs.slice(0, start) + catalogue + docs.slice(end + END.length);
    writeFileSync(DOCS_PATH, next);
    console.log("Wrote the field catalogue to docs/event-schema-versioning.md");
    return;
  }

  const sites = extractEmitSites();
  const problems = findProblems(schema, sites, docs);
  if (problems.length > 0) {
    console.error(`Event schema check failed (${problems.length} problem(s)):\n`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log(`Event schemas match ${sites.length} emit sites across ${Object.keys(schema.kinds).length} contracts.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
